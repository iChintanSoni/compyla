//! The pptx renderer (markdown-spec.md §8, architecture.md D12): a composed deck, written into a
//! template package. The template's masters, layouts, theme and other parts are kept; its slides
//! are replaced by the deck's, each referencing a template layout. Placeholders carry no geometry or
//! formatting of their own unless their content needs it, so they inherit the layout's.
//!
//! Slide, media and relationship identifiers are assigned in document order, and parts are written
//! in a fixed order, so the bytes are reproducible (§13).

