/// The house template (architecture.md D12), generated by `house/make_house.py`.
pub const HOUSE: &[u8] = include_bytes!("../house/house.potx");

const A: &str = "http://schemas.openxmlformats.org/drawingml/2006/main";
const P: &str = "http://schemas.openxmlformats.org/presentationml/2006/main";
const PML: &str = "application/vnd.openxmlformats-officedocument.presentationml";
const REL: &str = "http://schemas.openxmlformats.org/officeDocument/2006/relationships";
/// Medium Style 2 - Accent 1, built into every Office application.
const TABLE_STYLE: &str = "{5C22544A-7EE6-4342-B048-85BDC9FD1C3A}";
/// The standard 16:9 title and body areas, where a template's master has none.
const TITLE_AREA: Rect = Rect {
    x: 838_200,
    y: 365_125,
    cx: 10_515_600,
    cy: 1_325_563,
};
const BODY_AREA: Rect = Rect {
    x: 838_200,
    y: 1_825_625,
    cx: 10_515_600,
    cy: 4_351_338,
};
/// A table row's height: PowerPoint grows a row to fit its text.
const ROW_HEIGHT: i64 = 370_840;

/// The house template, read.
pub fn house() -> Template {
    Template::read(HOUSE).expect("the house template is a valid package")
}

/// The bytes of an image source, already resolved by the host (`None` when they aren't
/// available, which shows the alt text, §5).
pub type Images<'a> = dyn Fn(&str) -> Option<Vec<u8>> + 'a;

/// A rendered deck.
#[derive(Debug)]
pub struct Rendered {
    pub bytes: Vec<u8>,
    /// What the template's kept parts had removed (§10.4), with each part's name, in package
    /// order.
    pub removed: Vec<(String, Removed)>,
}

/// Renders `deck` into `template`.
pub fn render(
    deck: &Deck,
    template: &Template,
    properties: &Properties,
    images: &Images<'_>,
) -> Result<Rendered, Invalid> {
    let layouts = layouts::read(template)?;
    if layouts.is_empty() {
        return Err(Invalid("has no slide layouts".into()));
    }
    // The presentation part keeps nothing active or external either (§10.4).
    let main = sanitize::part(template, &template.main)?;
    let main_rels = main.relationships.clone();
    let notes_master = main_rels
        .iter()
        .find(|r| r.kind.ends_with("/notesMaster") && !r.external)
        .map(|r| r.target.clone());
    let table_style = template
        .related(&template.main, "tableStyles")?
        .and_then(|part| template.xml(&part).ok().flatten())
        .and_then(|styles| styles.attr("def").map(str::to_string))
        .unwrap_or_else(|| TABLE_STYLE.to_string());

    let mut new_parts: Vec<(String, String, Vec<u8>)> = Vec::new();
    let mut new_rels: HashMap<String, Vec<String>> = HashMap::new();
    // New media never take a name the template uses: its masters and layouts may refer to it.
    let mut media = Media {
        taken: template
            .parts()
            .map(|(name, _)| name.to_ascii_lowercase())
            .collect(),
        ..Media::default()
    };
    let mut slide_list = Vec::new();
    let mut presentation_rels = Relationships::new();
    // The template's own relationships stay, but not its slides.
    let kept: Vec<_> = main_rels
        .iter()
        .filter(|r| !r.kind.ends_with("/slide"))
        .collect();

    // Each layout's content placeholders, found once however many slides use it.
    let contents: Vec<Vec<&Placeholder>> = layouts.iter().map(Layout::content).collect();
    for (index, slide) in deck.slides.iter().enumerate() {
        // Bound by validation when a template is supplied; the house template binds here.
        let bound = slide
            .template
            .filter(|&index| index < layouts.len())
            .unwrap_or_else(|| bind(slide.layout, &layouts));
        let layout = &layouts[bound];
        let part = format!("ppt/slides/slide{}.xml", index + 1);
        let mut rels = Relationships::new();
        let mut targets = Vec::new();
        rels.add(
            &format!("{REL}/slideLayout"),
            &relative("ppt/slides", &layout.part),
        );
        targets.push(layout.part.clone());
        let xml = SlideWriter {
            rels: &mut rels,
            targets: &mut targets,
            deck,
            media: &mut media,
            images,
            from: "ppt/slides",
            next_id: 2,
            table_style: &table_style,
            lang: properties.language.as_deref(),
            notes: false,
        }
        .slide(slide, layout, &contents[bound]);
        if let Some(master) = &notes_master
            && !slide.notes.is_empty()
        {
            let notes_part = format!("ppt/notesSlides/notesSlide{}.xml", index + 1);
            let mut notes_rels = Relationships::new();
            let mut notes_targets = Vec::new();
            notes_rels.add(
                &format!("{REL}/notesMaster"),
                &relative("ppt/notesSlides", master),
            );
            notes_rels.add(&format!("{REL}/slide"), &relative("ppt/notesSlides", &part));
            notes_targets.extend([master.clone(), part.clone()]);
            let notes_xml = SlideWriter {
                rels: &mut notes_rels,
                targets: &mut notes_targets,
                deck,
                media: &mut media,
                images,
                from: "ppt/notesSlides",
                next_id: 2,
                table_style: &table_style,
                lang: properties.language.as_deref(),
                notes: true,
            }
            .notes(&slide.notes);
            rels.add(
                &format!("{REL}/notesSlide"),
                &relative("ppt/slides", &notes_part),
            );
            targets.push(notes_part.clone());
            new_parts.push((
                notes_part.clone(),
                format!("{PML}.notesSlide+xml"),
                notes_xml,
            ));
            new_parts.push((
                rels_name(&notes_part),
                package::RELATIONSHIPS.into(),
                notes_rels.to_xml(),
            ));
            new_rels.insert(notes_part, notes_targets);
        }
        new_parts.push((part.clone(), format!("{PML}.slide+xml"), xml));
        new_parts.push((
            rels_name(&part),
            package::RELATIONSHIPS.into(),
            rels.to_xml(),
        ));
        new_rels.insert(part.clone(), targets);
        slide_list.push((256 + index as u32, format!("cmpSlide{}", index + 1)));
    }

    // The presentation's relationships: the template's own, then the slides.
    let mut presentation_targets = Vec::new();
    // Kept with their ids: the presentation part refers to them.
    let main_folder = template
        .main
        .rsplit_once('/')
        .map_or("", |(f, _)| f)
        .to_string();
    for rel in &kept {
        if rel.external {
            presentation_rels.add_with_id(&rel.id, &rel.kind, &rel.target, true);
        } else {
            presentation_rels.add_with_id(
                &rel.id,
                &rel.kind,
                &relative(&main_folder, &rel.target),
                false,
            );
            presentation_targets.push(rel.target.clone());
        }
    }
    for (index, (_, id)) in slide_list.iter().enumerate() {
        let part = format!("ppt/slides/slide{}.xml", index + 1);
        presentation_rels.add_with_id(
            id,
            &format!("{REL}/slide"),
            &relative(&main_folder, &part),
            false,
        );
        presentation_targets.push(part);
    }
    let presentation = presentation::edit(
        main.xml
            .as_deref()
            .unwrap_or_else(|| template.part(&template.main).unwrap_or_default()),
        &slide_list,
    )
    .map_err(|why| {
        Invalid(format!(
            "has a presentation part that can't be edited: {why}"
        ))
    })?;
    new_rels.insert(template.main.clone(), presentation_targets);
    for (name, data) in media.parts {
        new_parts.push((name, String::new(), data));
    }

    assemble(
        template,
        properties,
        Presentation {
            xml: presentation,
            rels: presentation_rels,
            sanitized: main,
        },
        new_parts,
        &new_rels,
    )
}

/// The presentation part as written: edited, with its relationships, and what it had removed.
struct Presentation {
    xml: Vec<u8>,
    rels: Relationships,
    sanitized: sanitize::Part,
}

/// The house template's layout a house layout binds to (§8.5): by name, then by OOXML type, then
/// the Title and Content type (`obj`), then the first layout.
fn bind(layout: HouseLayout, layouts: &[Layout]) -> usize {
    let fold = compyla_core::validate::fold;
    let wanted = fold(layout.name());
    let of_kind = |kind: &str| layouts.iter().position(|l| l.kind.as_deref() == Some(kind));
    layouts
        .iter()
        .position(|l| fold(&l.name) == wanted)
        .or_else(|| layout.kind().and_then(of_kind))
        .or_else(|| of_kind("obj"))
        .unwrap_or(0)
}

/// The relationships part of `part`.
fn rels_name(part: &str) -> String {
    let (folder, file) = part.rsplit_once('/').unwrap_or(("", part));
    format!("{folder}/_rels/{file}.rels")
}

/// The placeholder each slot's blocks go into (§8.8): slot `i` the `i`-th content placeholder. A
/// slot past the last (a layout bound by fallback can have fewer placeholders than the house layout
/// has slots) shares the last rather than overlap it, and a layout with none lays all the content
/// out in one free area (`None`). Empty slots are left out.
fn assign<'p>(
    slots: &[Vec<Content>],
    content: &[&'p Placeholder],
) -> Vec<(Vec<Content>, Option<&'p Placeholder>)> {
    let mut out: Vec<(Vec<Content>, Option<&Placeholder>)> = Vec::new();
    for (index, blocks) in slots.iter().enumerate() {
        if blocks.is_empty() {
            continue;
        }
        let placeholder = content.get(index).or(content.last()).copied();
        let same = |last: Option<&Placeholder>| match (placeholder, last) {
            (Some(a), Some(b)) => std::ptr::eq(a, b),
            (None, None) => true,
            _ => false,
        };
        match out.last_mut() {
            Some((shared, last)) if same(*last) => shared.extend(blocks.iter().cloned()),
            _ => out.push((blocks.clone(), placeholder)),
        }
    }
    out
}

/// The order to read areas in (§8.8): areas that overlap horizontally form a column (joined
/// transitively), columns go left to right, and each column top to bottom. So a caption beside a
/// picture is read after the title above it, not after the picture, and a placeholder nudged off a
/// column's edge stays in its column. Areas not known come last, in order.
fn reading_order(areas: &[Option<Rect>]) -> Vec<usize> {
    fn root(parent: &mut [usize], mut i: usize) -> usize {
        while parent[i] != i {
            parent[i] = parent[parent[i]];
            i = parent[i];
        }
        i
    }
    let mut parent: Vec<usize> = (0..areas.len()).collect();
    for i in 0..areas.len() {
        for j in i + 1..areas.len() {
            if let (Some(a), Some(b)) = (areas[i], areas[j])
                && a.x < b.x + b.cx
                && b.x < a.x + a.cx
            {
                let (ri, rj) = (root(&mut parent, i), root(&mut parent, j));
                parent[ri.max(rj)] = ri.min(rj);
            }
        }
    }
    let columns: Vec<usize> = (0..areas.len()).map(|i| root(&mut parent, i)).collect();
    // Each column's left edge.
    let mut left: HashMap<usize, i64> = HashMap::new();
    for (area, &column) in areas.iter().zip(&columns) {
        if let Some(area) = area {
            let edge = left.entry(column).or_insert(area.x);
            *edge = (*edge).min(area.x);
        }
    }
    let mut order: Vec<usize> = (0..areas.len()).collect();
    order.sort_by_key(|&i| match areas[i] {
        Some(area) => (0, left[&columns[i]], columns[i], area.y, area.x),
        None => (1, 0, i, 0, 0),
    });
    order
}

/// `target`, a part name, relative to the folder `from`.
fn relative(from: &str, target: &str) -> String {
    let from: Vec<&str> = from.split('/').filter(|s| !s.is_empty()).collect();
    let to: Vec<&str> = target.split('/').collect();
    let common = from.iter().zip(&to).take_while(|(a, b)| a == b).count();
    let mut out: Vec<&str> = vec![".."; from.len() - common];
    out.extend(&to[common..]);
    out.join("/")
}

/// The deck's images, each written once.
#[derive(Default)]
struct Media {
    /// Source → part, pixel size as stored, and EXIF orientation.
    by_source: HashMap<String, (String, (u32, u32), u8)>,
    parts: Vec<(String, Vec<u8>)>,
    /// Part names in use, lowercased.
    taken: HashSet<String>,
}

struct SlideWriter<'a> {
    rels: &'a mut Relationships,
    /// The parts this part's relationships reach, for pruning the package.
    targets: &'a mut Vec<String>,
    deck: &'a Deck,
    media: &'a mut Media,
    images: &'a Images<'a>,
    /// The folder of the part being written, for relative targets.
    from: &'static str,
    next_id: u32,
    table_style: &'a str,
    /// The language of the text (`lang`, §2).
    lang: Option<&'a str>,
    /// Speaker notes: plain text, and no jumps to slides (§8.8).
    notes: bool,
}

impl SlideWriter<'_> {
    fn id(&mut self) -> String {
        let id = self.next_id;
        self.next_id += 1;
        id.to_string()
    }

    /// The relationship for a link, or `None` for a fragment that matches no slide.
    fn link(&mut self, url: &str) -> Option<LinkTarget> {
        match url.strip_prefix('#') {
            // A notes page's relationship to its slide must stay its only slide relationship.
            Some(_) if self.notes => None,
            Some(fragment) => {
                let slide = *self.deck.anchors.get(&percent_decoded(fragment))?;
                let part = format!("ppt/slides/slide{}.xml", slide + 1);
                let id = self
                    .rels
                    .add(&format!("{REL}/slide"), &relative(self.from, &part));
                Some((id, Some("ppaction://hlinksldjump")))
            }
            None => Some((self.rels.add_external(HYPERLINK, &package::uri(url)), None)),
        }
    }

    fn slide(&mut self, slide: &Slide, layout: &Layout, content: &[&Placeholder]) -> Vec<u8> {
        let mut shapes = Writer::fragment();
        match (&slide.title, layout.title()) {
            // The title's paragraph has no properties of its own: the layout's title style applies.
            (Some(title), Some(placeholder)) => {
                self.text_shape(&mut shapes, placeholder, None, Bullets::Inherit, |text| {
                    text.cell(title, None);
                })
            }
            // A layout without a title placeholder (Blank): the title is a title placeholder of
            // its own over the master's title area, so it is still the slide's title, and never
            // dropped (§8.8).
            (Some(title), None) => {
                let area = layout.master_title.unwrap_or(TITLE_AREA);
                let placeholder = Placeholder {
                    kind: "title".into(),
                    index: None,
                    rect: Some(area),
                };
                self.text_shape(
                    &mut shapes,
                    &placeholder,
                    Some(area),
                    Bullets::Inherit,
                    |text| text.cell(title, None),
                );
            }
            (None, _) => {}
        }
        // Content for a slot the layout has no placeholder for goes in a shape of its own over the
        // master's body area.
        let free = Placeholder {
            kind: String::new(),
            index: None,
            rect: Some(layout.master_body.unwrap_or(BODY_AREA)),
        };
        let slots = assign(&slide.slots, content);
        let areas: Vec<Option<Rect>> = slots
            .iter()
            .map(|(_, placeholder)| placeholder.unwrap_or(&free).rect)
            .collect();
        for index in reading_order(&areas) {
            let (blocks, placeholder) = &slots[index];
            match placeholder {
                Some(placeholder) => self.slot(&mut shapes, blocks, placeholder),
                None => self.free_slot(&mut shapes, blocks, &free),
            }
        }
        let mut xml = Writer::new();
        xml.open(
            "p:sld",
            &[("xmlns:a", A), ("xmlns:r", REL_NS), ("xmlns:p", P)],
        );
        xml.open("p:cSld", &[]);
        tree(&mut xml, &shapes.into_string());
        xml.close("p:cSld");
        xml.open("p:clrMapOvr", &[]);
        xml.empty("a:masterClrMapping", &[]);
        xml.close("p:clrMapOvr");
        xml.close("p:sld");
        xml.finish()
    }

    fn notes(&mut self, notes: &[Block]) -> Vec<u8> {
        let mut shapes = Writer::fragment();
        shapes.raw(r#"<p:sp><p:nvSpPr><p:cNvPr id="2" name="Slide Image Placeholder 1"/><p:cNvSpPr><a:spLocks noGrp="1" noRot="1" noChangeAspect="1"/></p:cNvSpPr><p:nvPr><p:ph type="sldImg"/></p:nvPr></p:nvSpPr><p:spPr/></p:sp>"#);
        self.next_id = 3;
        let placeholder = Placeholder {
            kind: "body".into(),
            index: Some(1),
            rect: None,
        };
        self.text_shape(&mut shapes, &placeholder, None, Bullets::Explicit, |text| {
            text.blocks(notes, 0, false, false);
        });
        let mut xml = Writer::new();
        xml.open(
            "p:notes",
            &[("xmlns:a", A), ("xmlns:r", REL_NS), ("xmlns:p", P)],
        );
        xml.open("p:cSld", &[]);
        tree(&mut xml, &shapes.into_string());
        xml.close("p:cSld");
        xml.open("p:clrMapOvr", &[]);
        xml.empty("a:masterClrMapping", &[]);
        xml.close("p:clrMapOvr");
        xml.close("p:notes");
        xml.finish()
    }

    /// A slot's blocks (§8.6). Text, code and quotes share the placeholder's text body. A slot with
    /// a table or an image, and more than one block, divides its height among them in order; the
    /// first keeps the placeholder, the rest are free shapes.
    fn slot(&mut self, out: &mut Writer, blocks: &[Content], placeholder: &Placeholder) {
        let bullets = if placeholder.kind == "obj" {
            Bullets::Inherit
        } else {
            Bullets::Explicit
        };
        let text_like =
            |c: &Content| matches!(c, Content::Text(_) | Content::Code(_) | Content::Quote(_));
        if blocks.iter().all(text_like) {
            self.text_shape(out, placeholder, None, bullets, |text| {
                for block in blocks {
                    content_text(text, block);
                }
            });
            return;
        }
        let rect = placeholder.rect.unwrap_or(BODY_AREA);
        let count = blocks.len() as i64;
        for (index, block) in blocks.iter().enumerate() {
            let band = if count == 1 {
                rect
            } else {
                let height = rect.cy / count;
                Rect {
                    y: rect.y + height * index as i64,
                    cy: height,
                    ..rect
                }
            };
            let placeholder = (index == 0).then_some(placeholder);
            let geometry = (count > 1).then_some(band);
            // A table or an image takes the placeholder only where it can hold one.
            let holds = |kinds: &[&str]| placeholder.filter(|p| kinds.contains(&p.kind.as_str()));
            match block {
                Content::Table(table) => self.table(out, table, holds(&["obj", "tbl"]), band),
                Content::Media(media, fit) => {
                    self.picture(out, media, *fit, holds(&["obj", "pic"]), band, geometry)
                }
                other => match placeholder {
                    Some(placeholder) => {
                        self.text_shape(out, placeholder, geometry, bullets, |text| {
                            content_text(text, other)
                        })
                    }
                    None => self.text_box(out, band, |text| content_text(text, other)),
                },
            }
        }
    }

    /// A slot's blocks with no placeholder to hold them: each a shape of its own, the slot's area
    /// divided among them in order.
    fn free_slot(&mut self, out: &mut Writer, blocks: &[Content], area: &Placeholder) {
        let rect = area.rect.unwrap_or(BODY_AREA);
        let text_like =
            |c: &Content| matches!(c, Content::Text(_) | Content::Code(_) | Content::Quote(_));
        if blocks.iter().all(text_like) {
            self.text_box(out, rect, |text| {
                for block in blocks {
                    content_text(text, block);
                }
            });
            return;
        }
        let count = blocks.len() as i64;
        for (index, block) in blocks.iter().enumerate() {
            let height = rect.cy / count;
            let band = Rect {
                y: rect.y + height * index as i64,
                cy: height,
                ..rect
            };
            match block {
                Content::Table(table) => self.table(out, table, None, band),
                Content::Media(media, fit) => self.picture(out, media, *fit, None, band, None),
                other => self.text_box(out, band, |text| content_text(text, other)),
            }
        }
    }

    /// A placeholder shape with text, with its own geometry only when `rect` is given.
    fn text_shape(
        &mut self,
        out: &mut Writer,
        placeholder: &Placeholder,
        rect: Option<Rect>,
        bullets: Bullets,
        write: impl FnOnce(&mut Text<'_, '_>),
    ) {
        let id = self.id();
        out.open("p:sp", &[]);
        out.open("p:nvSpPr", &[]);
        out.empty(
            "p:cNvPr",
            &[
                ("id", &id),
                ("name", &format!("{} {id}", placeholder_name(placeholder))),
            ],
        );
        out.open("p:cNvSpPr", &[]);
        out.empty("a:spLocks", &[("noGrp", "1")]);
        out.close("p:cNvSpPr");
        out.open("p:nvPr", &[]);
        ph(out, placeholder);
        out.close("p:nvPr");
        out.close("p:nvSpPr");
        match rect {
            Some(rect) => {
                out.open("p:spPr", &[]);
                xfrm(out, rect);
                out.close("p:spPr");
            }
            None => out.empty("p:spPr", &[]),
        }
        self.body(out, bullets, write);
        out.close("p:sp");
    }

    /// A text box: a shape of its own, for a slot's further text blocks.
    fn text_box(&mut self, out: &mut Writer, rect: Rect, write: impl FnOnce(&mut Text<'_, '_>)) {
        let id = self.id();
        out.open("p:sp", &[]);
        out.open("p:nvSpPr", &[]);
        out.empty(
            "p:cNvPr",
            &[("id", &id), ("name", &format!("TextBox {id}"))],
        );
        out.empty("p:cNvSpPr", &[("txBox", "1")]);
        out.empty("p:nvPr", &[]);
        out.close("p:nvSpPr");
        out.open("p:spPr", &[]);
        xfrm(out, rect);
        out.open("a:prstGeom", &[("prst", "rect")]);
        out.empty("a:avLst", &[]);
        out.close("a:prstGeom");
        out.empty("a:noFill", &[]);
        out.close("p:spPr");
        self.body(out, Bullets::Explicit, write);
        out.close("p:sp");
    }

    fn body(&mut self, out: &mut Writer, bullets: Bullets, write: impl FnOnce(&mut Text<'_, '_>)) {
        out.open("p:txBody", &[]);
        out.empty("a:bodyPr", &[]);
        out.empty("a:lstStyle", &[]);
        let (lang, plain) = (self.lang, self.notes);
        let mut links = |url: &str| self.link(url);
        let mut text = Text::new(out, &mut links, bullets, lang, plain);
        write(&mut text);
        text.finish();
        out.close("p:txBody");
    }

    fn table(
        &mut self,
        out: &mut Writer,
        table: &Table,
        placeholder: Option<&Placeholder>,
        rect: Rect,
    ) {
        let columns = std::iter::once(&table.header)
            .chain(&table.rows)
            .map(Vec::len)
            .max()
            .unwrap_or(1)
            .max(1);
        let rows = 1 + table.rows.len() as i64;
        let id = self.id();
        out.open("p:graphicFrame", &[]);
        out.open("p:nvGraphicFramePr", &[]);
        out.empty("p:cNvPr", &[("id", &id), ("name", &format!("Table {id}"))]);
        out.open("p:cNvGraphicFramePr", &[]);
        out.empty("a:graphicFrameLocks", &[("noGrp", "1")]);
        out.close("p:cNvGraphicFramePr");
        match placeholder {
            Some(placeholder) => {
                out.open("p:nvPr", &[]);
                ph(out, placeholder);
                out.close("p:nvPr");
            }
            None => out.empty("p:nvPr", &[]),
        }
        out.close("p:nvGraphicFramePr");
        let frame = Rect {
            cy: (ROW_HEIGHT * rows).min(rect.cy.max(ROW_HEIGHT)),
            ..rect
        };
        transform(out, "p:xfrm", &[], frame);
        out.open("a:graphic", &[]);
        out.open(
            "a:graphicData",
            &[(
                "uri",
                "http://schemas.openxmlformats.org/drawingml/2006/table",
            )],
        );
        out.open("a:tbl", &[]);
        out.open("a:tblPr", &[("firstRow", "1"), ("bandRow", "1")]);
        out.element("a:tableStyleId", &[], self.table_style);
        out.close("a:tblPr");
        out.open("a:tblGrid", &[]);
        let width = frame.cx / columns as i64;
        for column in 0..columns {
            let w = if column + 1 == columns {
                frame.cx - width * (columns as i64 - 1)
            } else {
                width
            };
            out.empty("a:gridCol", &[("w", &w.max(0).to_string())]);
        }
        out.close("a:tblGrid");
        let height = ROW_HEIGHT.to_string();
        for row in std::iter::once(&table.header).chain(&table.rows) {
            out.open("a:tr", &[("h", &height)]);
            for column in 0..columns {
                let align = table.align.get(column).copied().flatten().map(|a| match a {
                    compyla_core::ir::Align::Left => "l",
                    compyla_core::ir::Align::Center => "ctr",
                    compyla_core::ir::Align::Right => "r",
                });
                let runs = row
                    .get(column)
                    .map(|cell| cell.runs.clone())
                    .unwrap_or_default();
                out.open("a:tc", &[]);
                self.body_tag(out, "a:txBody", |text| text.cell(&runs, align));
                out.empty("a:tcPr", &[]);
                out.close("a:tc");
            }
            out.close("a:tr");
        }
        out.close("a:tbl");
        out.close("a:graphicData");
        out.close("a:graphic");
        out.close("p:graphicFrame");
    }

    fn body_tag(&mut self, out: &mut Writer, tag: &str, write: impl FnOnce(&mut Text<'_, '_>)) {
        out.open(tag, &[]);
        out.empty("a:bodyPr", &[]);
        out.empty("a:lstStyle", &[]);
        let (lang, plain) = (self.lang, self.notes);
        let mut links = |url: &str| self.link(url);
        let mut text = Text::new(out, &mut links, Bullets::Explicit, lang, plain);
        write(&mut text);
        text.finish();
        out.close(tag);
    }

    /// An image in `rect`: whole inside it (`contain`), or covering it, cropped (`cover`, §8.4). An
    /// image whose bytes aren't available, or can't be read, shows its alt text (§5).
    #[allow(clippy::too_many_arguments)]
    fn picture(
        &mut self,
        out: &mut Writer,
        media: &Media_,
        fit: Fit,
        placeholder: Option<&Placeholder>,
        rect: Rect,
        geometry: Option<Rect>,
    ) {
        let Some((target, (width, height), orientation)) = self.image(&media.src) else {
            // The alt text takes the image's share of the slot, without a bullet (§5, §8.8).
            match placeholder {
                Some(placeholder) => {
                    self.text_shape(out, placeholder, geometry, Bullets::Explicit, |text| {
                        text.alt_paragraph(&media.alt)
                    })
                }
                None => self.text_box(out, rect, |text| text.alt_paragraph(&media.alt)),
            }
            return;
        };
        let relationship = self
            .rels
            .add(&format!("{REL}/image"), &relative(self.from, &target));
        self.targets.push(target);
        let link = media.link.as_deref().and_then(|url| self.link(url));
        let id = self.id();
        out.open("p:pic", &[]);
        out.open("p:nvPicPr", &[]);
        let name = format!("Picture {id}");
        let attrs = [
            ("id", id.as_str()),
            ("name", name.as_str()),
            ("descr", media.alt.as_str()),
        ];
        match &link {
            Some((link, action)) => {
                out.open("p:cNvPr", &attrs);
                let mut link_attrs = vec![("r:id", link.as_str())];
                if let Some(action) = action {
                    link_attrs.push(("action", action));
                }
                out.empty("a:hlinkClick", &link_attrs);
                out.close("p:cNvPr");
            }
            None => out.empty("p:cNvPr", &attrs),
        }
        out.open("p:cNvPicPr", &[]);
        out.empty("a:picLocks", &[("noGrp", "1"), ("noChangeAspect", "1")]);
        out.close("p:cNvPicPr");
        match placeholder {
            Some(placeholder) => {
                out.open("p:nvPr", &[]);
                ph(out, placeholder);
                out.close("p:nvPr");
            }
            None => out.empty("p:nvPr", &[]),
        }
        out.close("p:nvPicPr");
        out.open("p:blipFill", &[]);
        out.empty("a:blip", &[("r:embed", &relationship)]);
        // EXIF orientation (§8.8): the picture is turned and flipped so the image shows upright,
        // and fitted by its upright shape. A quarter turn swaps the stored width and height.
        let quarter = (5..=8).contains(&orientation);
        let (w, h) = if quarter {
            (f64::from(height), f64::from(width))
        } else {
            (f64::from(width), f64::from(height))
        };
        let (rw, rh) = (rect.cx as f64, rect.cy as f64);
        let placed = match fit {
            Fit::Contain => {
                let scale = (rw / w).min(rh / h);
                let (cx, cy) = ((w * scale).round() as i64, (h * scale).round() as i64);
                Rect {
                    x: rect.x + (rect.cx - cx) / 2,
                    y: rect.y + (rect.cy - cy) / 2,
                    cx,
                    cy,
                }
            }
            Fit::Cover => {
                // Crop the image's overflow evenly from both sides, in thousandths of a percent.
                let scale = (rw / w).max(rh / h);
                // At most 49.999% from each side, so some of the image always shows.
                let crop = |image: f64, frame: f64| {
                    ((((image * scale - frame) / (image * scale)) * 50_000.0).round() as i64)
                        .clamp(0, 49_999)
                };
                let (x, y) = (crop(w, rw), crop(h, rh));
                // The crop is on the stored image's axes.
                let (x, y) = if quarter { (y, x) } else { (x, y) };
                if x > 0 || y > 0 {
                    let (x, y) = (x.to_string(), y.to_string());
                    out.empty("a:srcRect", &[("l", &x), ("t", &y), ("r", &x), ("b", &y)]);
                }
                rect
            }
        };
        out.open("a:stretch", &[]);
        out.empty("a:fillRect", &[]);
        out.close("a:stretch");
        out.close("p:blipFill");
        out.open("p:spPr", &[]);
        let (rot, flip_h, flip_v) = match orientation {
            2 => (0, true, false),
            3 => (10_800_000, false, false),
            4 => (0, false, true),
            5 => (5_400_000, false, true),
            6 => (5_400_000, false, false),
            7 => (5_400_000, true, false),
            8 => (16_200_000, false, false),
            _ => (0, false, false),
        };
        // A shape turned a quarter has its unturned size, centered where the upright box is.
        let shape = if quarter {
            Rect {
                x: placed.x + (placed.cx - placed.cy) / 2,
                y: placed.y + (placed.cy - placed.cx) / 2,
                cx: placed.cy,
                cy: placed.cx,
            }
        } else {
            placed
        };
        let rot = rot.to_string();
        let mut attrs = Vec::new();
        if rot != "0" {
            attrs.push(("rot", rot.as_str()));
        }
        if flip_h {
            attrs.push(("flipH", "1"));
        }
        if flip_v {
            attrs.push(("flipV", "1"));
        }
        transform(out, "a:xfrm", &attrs, shape);
        out.open("a:prstGeom", &[("prst", "rect")]);
        out.empty("a:avLst", &[]);
        out.close("a:prstGeom");
        out.close("p:spPr");
        out.close("p:pic");
    }

    /// The media part for an image source, written once per deck, with its pixel size.
    fn image(&mut self, src: &str) -> Option<(String, (u32, u32), u8)> {
        if let Some(found) = self.media.by_source.get(src) {
            return Some(found.clone());
        }
        let bytes = compyla_core::validate::data_uri(src).or_else(|| (self.images)(src))?;
        let extension = match compyla_core::validate::image_format(&bytes)? {
            "png" => "png",
            "jpeg" => "jpeg",
            "gif" => "gif",
            _ => return None,
        };
        let size = compyla_core::image::dimensions(&bytes)?;
        let orientation = compyla_core::image::orientation(&bytes);
        let mut number = self.media.parts.len() + 1;
        let part = loop {
            let part = format!("ppt/media/compyla{number}.{extension}");
            if self.media.taken.insert(part.to_ascii_lowercase()) {
                break part;
            }
            number += 1;
        };
        // The picture is turned by its shape (§8.8), so the copy written carries no turn of its own.
        let bytes = match compyla_core::image::as_stored(&bytes) {
            std::borrow::Cow::Owned(copy) => copy,
            std::borrow::Cow::Borrowed(_) => bytes,
        };
        self.media.parts.push((part.clone(), bytes));
        self.media
            .by_source
            .insert(src.to_string(), (part.clone(), size, orientation));
        Some((part, size, orientation))
    }
}

type Media_ = compyla_core::ir::Media;

fn content_text(text: &mut Text<'_, '_>, content: &Content) {
    match content {
        Content::Text(pieces) => text.pieces(pieces),
        Content::Code(code) => text.code(&code.value, 0, false),
        Content::Quote(quote) => text.blocks(&quote.children, 0, true, false),
        // Tables and images never share a text body (`slot`).
        Content::Table(_) | Content::Media(..) => {}
    }
}

fn placeholder_name(placeholder: &Placeholder) -> &'static str {
    match placeholder.kind.as_str() {
        "title" | "ctrTitle" => "Title",
        "subTitle" => "Subtitle",
        "pic" => "Picture Placeholder",
        "body" => "Text Placeholder",
        _ => "Content Placeholder",
    }
}

/// `p:ph` naming the layout's placeholder: its type (omitted for `obj`) and index.
fn ph(out: &mut Writer, placeholder: &Placeholder) {
    let index = placeholder.index.map(|i| i.to_string());
    let mut attrs = Vec::new();
    if placeholder.kind != "obj" {
        attrs.push(("type", placeholder.kind.as_str()));
    }
    if let Some(index) = &index {
        attrs.push(("idx", index.as_str()));
    }
    out.empty("p:ph", &attrs);
}

fn xfrm(out: &mut Writer, rect: Rect) {
    transform(out, "a:xfrm", &[], rect);
}

/// A transform element (`a:xfrm`, `p:xfrm`) placing `rect`, held to the schema's bounds.
fn transform(out: &mut Writer, element: &str, attrs: &[(&str, &str)], rect: Rect) {
    let rect = rect.bounded();
    out.open(element, attrs);
    out.empty(
        "a:off",
        &[("x", &rect.x.to_string()), ("y", &rect.y.to_string())],
    );
    out.empty(
        "a:ext",
        &[("cx", &rect.cx.to_string()), ("cy", &rect.cy.to_string())],
    );
    out.close(element);
}

fn tree(xml: &mut Writer, shapes: &str) {
    xml.open("p:spTree", &[]);
    xml.raw(r#"<p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr><p:grpSpPr/>"#);
    xml.raw(shapes);
    xml.close("p:spTree");
}

fn percent_decoded(text: &str) -> String {
    let bytes = text.as_bytes();
    let hex = |b: u8| (b as char).to_digit(16);
    let mut out = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%'
            && let (Some(h), Some(l)) = (
                bytes.get(i + 1).copied().and_then(hex),
                bytes.get(i + 2).copied().and_then(hex),
            )
        {
            out.push((h * 16 + l) as u8);
            i += 3;
        } else {
            out.push(bytes[i]);
            i += 1;
        }
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// The output package: the template's parts that are still reachable, without active or external
/// content (§10.4), with its presentation and properties replaced, then the new parts. Content
/// types are rebuilt for exactly these parts.
fn assemble(
    template: &Template,
    properties: &Properties,
    presentation: Presentation,
    new_parts: Vec<(String, String, Vec<u8>)>,
    new_rels: &HashMap<String, Vec<String>>,
) -> Result<Rendered, Invalid> {
    let main = template.main.clone();
    let main_rels = rels_name(&main);
    let new_names: HashSet<String> = new_parts
        .iter()
        .map(|(n, ..)| n.to_ascii_lowercase())
        .collect();
    let typed = |name: &str, kind: &str| {
        template
            .content_type(name)
            .is_some_and(|t| t.eq_ignore_ascii_case(&format!("{PML}.{kind}+xml")))
    };
    // The view settings' outline lists the template's slides, which are gone (§8.8): what it
    // relates to is neither followed nor kept.
    let viewed = |part: &str, kind: &str| typed(part, "viewProps") && kind.ends_with("/slide");
    // What the package reaches from its main part, following the relationships each template part
    // keeps once its active and external content is removed.
    let mut reachable: HashSet<String> = HashSet::new();
    let mut sanitized: HashMap<String, sanitize::Part> = HashMap::new();
    let mut queue = vec![main.clone()];
    while let Some(part) = queue.pop() {
        let lower = part.to_ascii_lowercase();
        if !reachable.insert(lower.clone()) {
            continue;
        }
        let targets: Vec<String> = match new_rels.get(&part) {
            Some(targets) => targets.clone(),
            None if new_names.contains(&lower) => Vec::new(),
            None => {
                let clean = sanitize::part(template, &part)?;
                let targets = clean
                    .relationships
                    .iter()
                    .filter(|r| !r.external && !viewed(&part, &r.kind))
                    .map(|r| r.target.clone())
                    .collect();
                sanitized.insert(lower, clean);
                targets
            }
        };
        queue.extend(targets);
    }
    let is_rels = |name: &str| name.to_ascii_lowercase().ends_with(".rels");
    let rels_owner = |name: &str| -> String {
        let (folder, file) = name.rsplit_once('/').unwrap_or(("", name));
        let folder = folder
            .strip_suffix("_rels")
            .unwrap_or(folder)
            .trim_end_matches('/');
        let file = file.strip_suffix(".rels").unwrap_or(file);
        if folder.is_empty() {
            file.to_string()
        } else {
            format!("{folder}/{file}")
        }
    };

    let mut entries: Vec<(String, Vec<u8>)> = Vec::new();
    let mut overrides: BTreeMap<String, String> = BTreeMap::new();
    let package_rels = package::package_relationships(&main);
    entries.push(("_rels/.rels".into(), package_rels.to_xml()));
    entries.push(("docProps/core.xml".into(), package::core_xml(properties)));
    overrides.insert(
        "docProps/core.xml".into(),
        package::CORE_PROPERTIES_TYPE.into(),
    );
    entries.push(("docProps/app.xml".into(), package::app_xml()));
    overrides.insert(
        "docProps/app.xml".into(),
        package::EXTENDED_PROPERTIES_TYPE.into(),
    );

    for (name, data) in template.parts() {
        let lower = name.to_ascii_lowercase();
        if name == "[Content_Types].xml" || lower == "_rels/.rels" || lower.starts_with("docprops/")
        {
            continue;
        }
        let keep = if is_rels(name) {
            reachable.contains(&rels_owner(name).to_ascii_lowercase())
        } else {
            reachable.contains(&lower)
        };
        if !keep || new_names.contains(&lower) {
            continue;
        }
        if name.eq_ignore_ascii_case(&main) {
            entries.push((name.to_string(), presentation.xml.clone()));
            overrides.insert(name.to_string(), format!("{PML}.presentation.main+xml"));
            continue;
        }
        if name.eq_ignore_ascii_case(&main_rels) {
            entries.push((name.to_string(), presentation.rels.to_xml()));
            continue;
        }
        let clean = sanitized.get(&rels_owner(name).to_ascii_lowercase());
        if is_rels(name) && typed(&rels_owner(name), "viewProps") {
            let owner = rels_owner(name);
            let folder = owner.rsplit_once('/').map_or("", |(f, _)| f);
            let mut kept = Relationships::new();
            for r in clean.iter().flat_map(|c| &c.relationships) {
                if viewed(&owner, &r.kind) {
                    continue;
                }
                let target = if r.external {
                    r.target.clone()
                } else {
                    relative(folder, &r.target)
                };
                kept.add_with_id(&r.id, &r.kind, &target, r.external);
            }
            if !kept.is_empty() {
                entries.push((name.to_string(), kept.to_xml()));
            }
            continue;
        }
        if is_rels(name) {
            let data = clean
                .and_then(|c| c.rels.clone())
                .unwrap_or_else(|| data.to_vec());
            entries.push((name.to_string(), data));
            continue;
        }
        let data = sanitized
            .get(&lower)
            .and_then(|c| c.xml.as_deref())
            .unwrap_or(data);
        if let Some(content_type) = template.content_type(name) {
            overrides.insert(name.to_string(), content_type.to_string());
        }
        // Show and view settings may name the template's slides or custom shows, which are gone.
        let data = if typed(name, "presProps") {
            presentation::show_properties(data)
                .map_err(|why| Invalid(format!("has show settings that can't be edited: {why}")))?
        } else if typed(name, "viewProps") {
            presentation::view_properties(data)
                .map_err(|why| Invalid(format!("has view settings that can't be edited: {why}")))?
        } else {
            data.to_vec()
        };
        entries.push((name.to_string(), data));
    }
    if !entries
        .iter()
        .any(|(n, _)| n.eq_ignore_ascii_case(&main_rels))
    {
        entries.push((main_rels, presentation.rels.to_xml()));
    }
    let mut extensions: BTreeMap<String, String> = template
        .defaults()
        .filter(|(e, _)| *e != "rels" && *e != "xml")
        .map(|(e, t)| (e.to_string(), t.to_string()))
        .collect();
    for (name, content_type, data) in new_parts {
        if content_type.is_empty() {
            let extension = name.rsplit_once('.').map_or("", |(_, e)| e).to_string();
            extensions.insert(extension.clone(), format!("image/{extension}"));
        } else if content_type != package::RELATIONSHIPS {
            overrides.insert(name.clone(), content_type);
        }
        entries.push((name, data));
    }

    let mut types = Writer::new();
    types.open(
        "Types",
        &[(
            "xmlns",
            "http://schemas.openxmlformats.org/package/2006/content-types",
        )],
    );
    types.empty(
        "Default",
        &[
            ("Extension", "rels"),
            ("ContentType", package::RELATIONSHIPS),
        ],
    );
    types.empty(
        "Default",
        &[("Extension", "xml"), ("ContentType", "application/xml")],
    );
    for (extension, content_type) in &extensions {
        types.empty(
            "Default",
            &[("Extension", extension), ("ContentType", content_type)],
        );
    }
    for (name, content_type) in &overrides {
        types.empty(
            "Override",
            &[
                ("PartName", &format!("/{name}")),
                ("ContentType", content_type),
            ],
        );
    }
    types.close("Types");
    entries.insert(0, ("[Content_Types].xml".into(), types.finish()));

    // What the kept template parts had removed, in package order.
    let mut removed = Vec::new();
    for (name, _) in template.parts() {
        let lower = name.to_ascii_lowercase();
        let clean = if name.eq_ignore_ascii_case(&main) {
            Some(&presentation.sanitized)
        } else {
            sanitized.get(&lower)
        };
        if let Some(clean) = clean {
            removed.extend(clean.removed.iter().map(|r| (name.to_string(), r.clone())));
        }
    }
    Ok(Rendered {
        bytes: compyla_ooxml::zip::write(&entries),
        removed,
    })
}

