"""Generates src/tables.rs, the Unicode properties measurement needs (markdown-spec.md §3, C62),
from the Unicode Character Database 17.0.0, the version `unicode-script` uses. Standard library
only; each input must match its pinned SHA-256:

    python3 -I crates/compyla-fonts/unicode/make_tables.py <dir holding the three UCD files>

The files are at https://www.unicode.org/Public/17.0.0/ucd/.
"""

import hashlib
import re
import sys
from pathlib import Path

VERSION = (17, 0, 0)
INPUTS = {
    "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    "EastAsianWidth.txt": "ea7ce50f3444a050333448dffef1cadd9325af55cbb764b4a2280faf52170a33",
    "DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
}
OUT = Path(__file__).resolve().parent.parent / "src" / "tables.rs"


def read(directory, name):
    data = (Path(directory) / name).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != INPUTS[name]:
        sys.exit(f"{name}: SHA-256 {digest}, want {INPUTS[name]}")
    return data.decode("utf-8")


def merged(points):
    """Sorted, merged inclusive ranges covering `points` (a set of code points)."""
    ranges = []
    for point in sorted(points):
        if ranges and ranges[-1][1] + 1 == point:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ranges


def span(field):
    first, _, last = field.strip().partition("..")
    return range(int(first, 16), int(last or first, 16) + 1)


def general_categories(text, wanted):
    points = {category: set() for category in wanted}
    for line in text.splitlines():
        fields = line.split(";")
        category = fields[2]
        if category in points:
            # No range entry (`<…, First>`) has one of these categories.
            assert not fields[1].endswith("First>"), line
            points[category].add(int(fields[0], 16))
    return points


def wide(text):
    points = set()
    for line in text.splitlines():
        # Unlisted code points default to N, except the ranges `@missing` lines give.
        missing = re.match(r"#\s*@missing:\s*([0-9A-F.]+)\s*;\s*(\w+)", line)
        body = line.split("#", 1)[0].strip()
        if missing:
            field, value = missing.groups()
        elif body:
            field, value = (part.strip() for part in body.split(";"))
        else:
            continue
        if value in ("W", "F"):
            points.update(span(field))
    return points


def default_ignorable(text):
    points = set()
    for line in text.splitlines():
        body = line.split("#", 1)[0].strip()
        if body:
            # Some properties take a value as a third field (`InCB; Linker`).
            field, prop = (part.strip() for part in body.split(";")[:2])
            if prop == "Default_Ignorable_Code_Point":
                points.update(span(field))
    return points


def table(name, doc, points):
    ranges = [f"(0x{a:04X}, 0x{b:04X})" for a, b in merged(points)]
    head = f"pub const {name}: &[(u32, u32)] = &["
    # As rustfmt writes it: on one line where that fits in 100 columns.
    line = head + ", ".join(ranges) + "];"
    if len(line) <= 100:
        return f"/// {doc}\n{line}\n"
    rows = "".join(f"    {r},\n" for r in ranges)
    return f"/// {doc}\n{head}\n{rows}];\n"


def main():
    directory = sys.argv[1]
    data = read(directory, "UnicodeData.txt")
    categories = general_categories(data, ("Mn", "Me", "Cc", "Zs"))
    out = (
        "//! Unicode properties for measurement (markdown-spec.md §3, C62), as inclusive code point\n"
        "//! ranges. Generated by `unicode/make_tables.py` from the Unicode Character Database\n"
        "//! 17.0.0; don't edit.\n\n"
        f"pub const UNICODE_VERSION: (u8, u8, u8) = {VERSION};\n\n"
        + table("WIDE", "East Asian Width Wide or Fullwidth (UAX #11).", wide(read(directory, "EastAsianWidth.txt"))) + "\n"
        + table("MARK", "General Category Mn or Me: nonspacing and enclosing marks.", categories["Mn"] | categories["Me"]) + "\n"
        + table("CONTROL", "General Category Cc.", categories["Cc"]) + "\n"
        + table("SPACE", "General Category Zs: space separators.", categories["Zs"]) + "\n"
        + table("DEFAULT_IGNORABLE", "Default_Ignorable_Code_Point (DerivedCoreProperties).",
                default_ignorable(read(directory, "DerivedCoreProperties.txt")))
    )
    OUT.write_text(out)


if __name__ == "__main__":
    main()
